#!/usr/bin/env bash
set -euo pipefail

# Build LilyGo's own factory firmware for the T-Watch S3 / S3 Plus, unchanged,
# from the vendor's PlatformIO project at a pinned commit (M0 hardware
# baseline). The vendor repo has no license file, so it is cloned into
# .baseline/ (gitignored) rather than copied into this repo.
#
# Prints the path of the built firmware.bin and records the resolved library
# versions in docs/baseline-build.md.

# shellcheck source=scripts/lib/common.sh
source "$(dirname "$0")/lib/common.sh"

VENDOR_REPO="https://github.com/Xinyuan-LilyGO/LilyGoLib-PlatformIO.git"
VENDOR_SHA="097c1bda9c6a2a847efd27ee4b3dbda3dc70a1b1" # pragma: allowlist secret (git commit id)
PIO_ENV="twatchs3"
# The vendor's espressif32@6.12.0 (Arduino 2.0.17 / IDF 4.4) can't compile
# LilyGoLib 0.2.x, which needs IDF 5 LCD APIs. Use pioarduino instead.
PLATFORM_URL="https://github.com/pioarduino/platform-espressif32/releases/download/55.03.39/platform-espressif32.zip"
WORK="${REPO_ROOT}/.baseline/LilyGoLib-PlatformIO"

main() {
  [[ $# -eq 0 ]] || die 2 "usage: $(basename "$0")"
  require_cmd git pio sha256sum

  if [[ ! -d "${WORK}/.git" ]]; then
    log "cloning vendor project"
    mkdir -p "$(dirname "${WORK}")"
    git clone --quiet "${VENDOR_REPO}" "${WORK}"
  fi
  git -C "${WORK}" fetch --quiet origin "${VENDOR_SHA}" 2> /dev/null || true
  git -C "${WORK}" checkout --quiet --force --detach "${VENDOR_SHA}"

  # Two changes to the vendor project, nothing else:
  #  1. its documented setup step, selecting the board via default_envs
  #     (src_dir and the partition table path are derived from it);
  #  2. the platform, see PLATFORM_URL above;
  #  3. ignore the registry "ESP32 BLE Arduino" package: it targets Arduino
  #     2.x and breaks on 3.x, which ships its own BLE library.
  sed -i -E \
    -e "s/^default_envs = tlora_pager.*/default_envs = ${PIO_ENV}/" \
    -e "s#^platform = espressif32@6\.12\.0#platform = ${PLATFORM_URL}#" \
    -e "s/^\[env:${PIO_ENV}\]$/[env:${PIO_ENV}]\nlib_ignore = ESP32 BLE Arduino/" \
    "${WORK}/platformio.ini"
  [[ "$(git -C "${WORK}" diff --numstat | awk '{print $1+$2}')" == "5" ]] ||
    die 1 "unexpected changes in ${WORK}; delete .baseline/ and re-run"

  log "building env ${PIO_ENV} at ${VENDOR_SHA:0:12}"
  (cd "${WORK}" && pio run -e "${PIO_ENV}") >&2 || die 1 "vendor build failed"

  local bin="${WORK}/.pio/build/${PIO_ENV}/firmware.bin"
  [[ -f "${bin}" ]] || die 1 "build finished but ${bin} is missing"

  {
    echo "# Baseline build (generated by scripts/build-baseline.sh)"
    echo
    echo "- Vendor project: \`${VENDOR_REPO}\` @ \`${VENDOR_SHA}\`"
    echo "- Env: \`${PIO_ENV}\` (changes: \`default_envs = ${PIO_ENV}\`, platform \`${PLATFORM_URL}\`, \`lib_ignore = ESP32 BLE Arduino\`)"
    echo "- firmware.bin sha256: \`$(sha256_of "${bin}")\`"
    echo "- Built: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo
    echo "## Resolved packages"
    echo
    echo '```text'
    (cd "${WORK}" && pio pkg list -e "${PIO_ENV}" 2> /dev/null) | sed -E "s#${HOME}#~#g"
    echo '```'
  } > "${REPO_ROOT}/docs/baseline-build.md"

  printf '%s\n' "${bin}"
}

main "$@"
